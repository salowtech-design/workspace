// Generates (or checks, with --check) docs/SHEETS_FUNCTIONS.md from the engine's own argument-count table and tests/js/function_sources.json.
// A function in the engine without a row in function_sources.json, or a row for a function the engine does not have, fails the check.
const fs = require("fs"), path = require("path");
const { functionArity, Sheet, isErr } = require("../../static/sheets/formula.js");
const root = path.join(__dirname, "../..");
const sources = JSON.parse(fs.readFileSync(path.join(__dirname, "function_sources.json"), "utf8"));
const ar = functionArity(), names = Object.keys(ar).sort();
const problems = [];
names.forEach((n) => { if (!sources[n]) problems.push("engine function without a row: " + n); });
Object.keys(sources).forEach((n) => { if (!ar[n]) problems.push("row for a function the engine does not have: " + n); });
// every listed function must be reachable: called with its smallest argument count it must not answer #NAME? (other errors are fine)
names.forEach((n) => {
  const args = new Array(ar[n][0]).fill("1").join(",");
  const got = new Sheet({ A1: "=" + n + "(" + args + ")" }).get("A1");
  if (isErr(got) && got.code === "#NAME?") problems.push("listed but answers #NAME?: " + n);
});
const lines = [
  "# Sheets functions in this engine (local subset)",
  "",
  "Generated by `node tests/js/function_table.js` from the engine's argument-count table and `tests/js/function_sources.json`. Do not edit by hand; `--check` fails if this file and the engine disagree.",
  "",
  `This lists the ${names.length} names in the engine's argument-count table, with the smallest and largest argument counts that table allows. It is not a claim of conformance with Google Sheets or Excel, and not a claim that each function behaves correctly: the check below only proves that each listed name, called with its smallest argument count, does not answer #NAME? (any other result, including an error, passes). It does not test the largest argument count. Where a Google Docs Editors Help page was read, its id is given (https://support.google.com/docs/answer/ID?hl=en); the rules that page does not state are this engine's own choices, written in the comments of static/sheets/formula.js. \"Not recorded\" means no page id was kept for that function, not that none was read.`,
  "",
  "| Function | Arguments | Help page id | Note |",
  "| --- | --- | --- | --- |",
];
names.forEach((n) => {
  const [lo, hi] = ar[n], s = sources[n] || {};
  lines.push(`| ${n} | ${lo === hi ? lo : lo + " to " + hi} | ${s.page || "not recorded"} | ${s.note || ""} |`);
});
lines.push("", `${names.length} functions in the table.`, "", "Not built (a hand-written list as of this commit, not checked by the test): array results that fill neighbouring cells other than a one-column SORT (FILTER, UNIQUE, SPLIT, TRANSPOSE; SORT fills a block under its cell only when its first argument is a one-column range), TEXT and number formats, REGEX functions, PERCENTILE, QUARTILE, STDEVA and the other text-counting variants, HOUR, MINUTE, SECOND, DAYS, NETWORKDAYS, finance functions, RAND and RANDBETWEEN.", "");
const text = lines.join("\n");
const file = path.join(root, "docs/SHEETS_FUNCTIONS.md");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) problems.push("docs/SHEETS_FUNCTIONS.md is out of date: run node tests/js/function_table.js");
  if (problems.length) { console.log(problems.join("\n")); process.exit(1); }
  console.log(`${names.length}/${names.length} functions have a row and the table is current`);
} else {
  if (problems.length) { console.log(problems.join("\n")); process.exit(1); }
  fs.writeFileSync(file, text); console.log("wrote", file, names.length, "functions");
}
