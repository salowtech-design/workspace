const M = require("../../static/sheets/model.js");
const F = require("../../static/sheets/formula.js");
let fails = 0, n = 0;
const ok = (d, c) => { n++; if (!c) { fails++; console.log("FAIL", d); } };
const addrOf = (c, r) => String.fromCharCode(64 + c) + r;
const imp = (t, check) => M.csvImport(t, check || null, addrOf, 26, 100, 2000);
const mk = (o) => Object.assign(Object.create(null), o);
let r = imp("name,qty\r\napple,3\r\npear,4\r\n");
ok("basic 3x2 file", r.rows === 3 && r.cols === 2 && r.set === 6 && r.cells.A1 === "name" && r.cells.B3 === "4" && !r.error);
r = imp("\uFEFFa,b\n1,2");
ok("a byte-order mark is dropped and a missing final newline is fine", r.cells.A1 === "a" && r.cells.B2 === "2");
r = imp('"x, y","say ""hi""","l1\nl2"\n');
ok("quoted commas, quotes and line breaks", r.cells.A1 === "x, y" && r.cells.B1 === 'say "hi"' && r.cells.C1 === "l1 l2" && r.breaks === 1);
ok("an unclosed quote is refused, nothing returned as cells", !!imp('"abc,def').error && !imp('"abc,def').cells);
ok("text after a closing quote is refused", !!imp('"abc"x,def').error);
r = imp("a,,c\n,,\n");
ok("empty cells stay empty and a blank row keeps its place", r.set === 2 && !("B1" in r.cells) && r.rows === 2);
r = imp("\"=SUM(1,2)\",=cmd|' /C calc'!A0,ok\n");
ok("a field starting with = is kept as text with a leading apostrophe, never a formula", r.cells.A1 === "'=SUM(1,2)" && r.cells.B1.charAt(0) === "'" && r.cells.C1 === "ok" && r.literal === 2 && !Object.values(r.cells).some((v) => v.charAt(0) === "="));
r = imp("12,0.5,-3,007\n");
ok("numbers are not converted: text kept exactly", r.cells.A1 === "12" && r.cells.D1 === "007" && r.cells.C1 === "-3");
r = imp(("1,".repeat(30) + "1\n").repeat(105));
ok("clips at Z100: Z100 is kept, AA1 and row 101 are not", r.cells.Z100 === "1" && !("AA1" in r.cells) && !("A101" in r.cells));
ok("clipped count is exactly the cells outside A1:Z100", r.clipped === 105 * 31 - 100 * 26);
r = imp("ok,bad\n", (a, v) => (v === "bad" ? "no" : null));
ok("a validation rule refuses a cell and it is counted", r.cells.A1 === "ok" && !("B1" in r.cells) && r.refused === 1);
ok("empty file refused", !!imp("").error);
ok("too many characters refused", !!imp("x".repeat(1000001)).error);
ok("too many rows refused", !!imp("1\n".repeat(5001)).error);
ok("too many columns refused", !!imp(",".repeat(200) + "\n").error);
r = imp("x".repeat(2001) + ",y\n");
ok("a cell over the cell limit is left out and counted", r.tooLong === 1 && r.cells.B1 === "y");
ok("only a blank file of separators gives zero cells, not an error", imp(",,\n").set === 0 && !imp(",,\n").error);
// Round trip through the real exporter (values shown, not formulas).
const cells = mk({ A1: "name", B1: "qty", A2: "say \"hi\", ok", B2: "5", A3: "line one", B3: "=B2*2", A4: "=1+1 typed as text?", B4: "+note", A5: "@mention", B5: "-x" });
// A4/A5.. hold text via sheet; make A4 a text cell by routing through the engine with an apostrophe-free literal.
const sh = new F.Sheet(cells);
const out = M.toCsv(cells, F.parseAddr, (a) => sh.get(a), F.isErr);
const back = imp(out.text);
ok("round trip: plain text, quotes, commas and numbers come back as the same text", back.cells.A1 === "name" && back.cells.A2 === 'say "hi", ok' && back.cells.B2 === "5" && back.cells.A3 === "line one");
ok("round trip: a formula comes back as its shown value, as text, not as a formula", back.cells.B3 === "10" && cells.B3 === "=B2*2");
ok("round trip: the exporter's apostrophe on + - @ text stays in the text (it is not removed)", ("B4" in back.cells) && ("A5" in back.cells) && back.cells.A5.indexOf("@mention") >= 0);
ok("round trip: nothing imported starts with =", Object.values(back.cells).every((v) => v.charAt(0) !== "="));
ok("round trip: same row and column box as the export", back.rows === out.rows && back.cols === out.cols);
// negative control: the same exporter file imported by the plain paste path would turn a leading = into a formula
const asPaste = M.applyPaste(mk({}), { rows: 1, cols: 1, items: [["=SUM(1,2)"]] }, 1, 1, 26, 100, 2000, null, addrOf);
ok("negative control: the paste path keeps = as a formula, so the import path differs on purpose", asPaste.cells.A1 === "=SUM(1,2)" && asPaste.formulas === 1);
console.log(`${n - fails}/${n} csv import rows passed`);
process.exit(fails ? 1 : 0);
