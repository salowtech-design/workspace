"""Repeat rules for calendar events: daily, weekly (chosen weekdays), monthly (same day of the
month). Build defaults, not user policy. Dates are generated on the local calendar of the
event's own zone, so a 10:00 slot stays 10:00 across a daylight-saving change.

Count semantics: the count is the number of occurrence DATES generated by the rule, starting at
the first one. A date whose local time does not exist (a spring-forward gap) still uses up one
of the count but is not shown. A local time that happens twice (fall back) uses the first one.
A monthly rule skips months without that day (the 31st) and does not count them."""

import datetime as dt
from zoneinfo import ZoneInfo

FREQS = ("daily", "weekly", "monthly")
MAX_COUNT = 200
MAX_INTERVAL = 12
MAX_SPAN_DAYS = 731  # an until date is at most about two years after the start
MAX_STEPS = 5000  # hard stop for any generator loop


def parse_weekdays(raw):
    return sorted({int(x) for x in (raw or "").split(",") if x.strip() != ""})


def local_dates(ev):
    """Yield the occurrence dates (local, in ev.tz) of a series in order, honouring count and
    until. Unbounded rules cannot exist (a count or an until is required)."""
    tz = ZoneInfo(ev.tz)
    d0 = ev.start_utc.astimezone(tz).date()
    n = 0
    steps = 0
    wds = parse_weekdays(ev.weekdays) if ev.freq == "weekly" else []
    k = 0
    while steps < MAX_STEPS:
        steps += 1
        if ev.freq == "daily":
            batch = [d0 + dt.timedelta(days=k * ev.interval)]
        elif ev.freq == "weekly":
            ws = d0 - dt.timedelta(days=d0.weekday()) + dt.timedelta(weeks=k * ev.interval)
            batch = [ws + dt.timedelta(days=w) for w in wds]
        else:  # monthly
            m = d0.month - 1 + k * ev.interval
            y, mo = d0.year + m // 12, m % 12 + 1
            try:
                batch = [dt.date(y, mo, d0.day)]
            except ValueError:
                batch = []
        k += 1
        for d in batch:
            if d < d0:
                continue
            if ev.until is not None and d > ev.until:
                return
            yield d
            n += 1
            if ev.count is not None and n >= ev.count:
                return
        if ev.until is None and ev.count is None:
            return  # no bound: refuse to run away


def occurrence(ev, d):
    """(start_utc, end_utc) of the occurrence on local date d, or None when that local time does
    not exist in the zone."""
    tz = ZoneInfo(ev.tz)
    t0 = ev.start_utc.astimezone(tz).time()
    naive = dt.datetime.combine(d, t0)
    aware = naive.replace(tzinfo=tz)
    s = aware.astimezone(dt.timezone.utc)
    if s.astimezone(tz).replace(tzinfo=None) != naive:
        return None
    return s, s + (ev.end_utc - ev.start_utc)


def expand(ev, win_start, win_end, skipped=frozenset()):
    """Occurrences of a series overlapping [win_start, win_end), as (local_date, start, end)."""
    out = []
    for d in local_dates(ev):
        if dt.datetime.combine(d, dt.time.min, tzinfo=dt.timezone.utc) > win_end + dt.timedelta(
            days=2
        ):
            break  # beyond the window (the 2 days cover any zone offset)
        if d in skipped:
            continue
        o = occurrence(ev, d)
        if o is None:
            continue
        if o[0] < win_end and o[1] > win_start:
            out.append((d, o[0], o[1]))
    return out


def last_end(ev):
    """End of the last shown occurrence (None if the rule yields none, which cannot happen for
    a first occurrence that exists)."""
    last = None
    for d in local_dates(ev):
        o = occurrence(ev, d)
        if o is not None:
            last = o[1]
    return last


def describe(ev):
    if not ev.freq:
        return ""
    every = "every" if ev.interval == 1 else f"every {ev.interval}"
    unit = {"daily": "day", "weekly": "week", "monthly": "month"}[ev.freq]
    unit = unit if ev.interval == 1 else unit + "s"
    s = f"Repeats {every} {unit}"
    if ev.freq == "weekly":
        names = "Mon Tue Wed Thu Fri Sat Sun".split()
        s += " on " + ", ".join(names[i] for i in parse_weekdays(ev.weekdays))
    if ev.freq == "monthly":
        s += " (months without that day are skipped)"
    if ev.count is not None:
        s += f", {ev.count} times"
    if ev.until is not None:
        s += f", until {ev.until:%-d %b %Y}"
    return s + "."
