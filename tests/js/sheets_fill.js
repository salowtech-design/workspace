const M = require("../../static/sheets/model.js");
const { parseAddr } = require("../../static/sheets/formula.js");
let fails = 0, n = 0;
const ok = (d, c) => { n++; if (!c) { fails++; console.log("FAIL", d); } };
const addrOf = (c, r) => String.fromCharCode(64 + c) + r;
const mk = (o) => Object.assign(Object.create(null), o);
const R = (t) => M.parseRange(t, parseAddr);
const fill = (cells, rg, dir, check) => M.fillRange(cells, R(rg), dir, check, addrOf, 2000);
let r = fill(mk({ A1: "x", B1: "y", A2: "old", A3: "keep" }), "A1:B3", "down");
ok("first row copied down over every other row", r.cells.A2 === "x" && r.cells.B2 === "y" && r.cells.A3 === "x" && r.cells.B3 === "y" && r.set === 4);
r = fill(mk({ A1: "x", B1: "y", B2: "old" }), "A1:C2", "right");
ok("first column copied right, an empty source cell clears its row", r.cells.B1 === "x" && r.cells.C1 === "x" && !("B2" in r.cells));
r = fill(mk({ A1: "x", A2: "1", B1: "y" }), "A1:C2", "right");
ok("right: each row takes its own first-column value", r.cells.B1 === "x" && r.cells.C1 === "x" && r.cells.B2 === "1" && r.cells.C2 === "1");
r = fill(mk({ A1: "=B1+1", A2: "old" }), "A1:A3", "down");
ok("without a shift function a formula is copied exactly", r.cells.A2 === "=B1+1" && r.cells.A3 === "=B1+1" && r.formulas === 2);
r = fill(mk({ A2: "old", A3: "old2" }), "A1:A3", "down");
ok("an empty source clears the targets", !("A2" in r.cells) && !("A3" in r.cells) && r.cleared === 2);
const base = mk({ A1: "x", A2: "old" }); fill(base, "A1:A2", "down");
ok("input cells untouched", base.A2 === "old");
ok("one row cannot be filled down", fill(mk({}), "A1:C1", "down").error);
ok("one column cannot be filled right", fill(mk({}), "A1:A5", "right").error);
r = fill(mk({ A1: "bad", A2: "keep" }), "A1:A3", "down", (a, v) => (v === "bad" ? "no" : null));
ok("refused values are counted and left alone", r.refused === 2 && r.cells.A2 === "keep" && !("A3" in r.cells));
r = M.fillRange(mk({ A1: "abcdef" }), R("A1:A2"), "down", null, addrOf, 3);
ok("too long text is counted and not copied", r.tooLong === 1 && !("A2" in r.cells));
r = fill(mk({ A1: "x", A2: "x" }), "A1:A2", "down");
ok("already matching changes nothing", r.set === 0 && r.cleared === 0);
const F = require("../../static/sheets/formula.js"), sh = F.shiftFormula;
const fs = (cells, rg, dir) => M.fillRange(mk(cells), R(rg), dir, null, addrOf, 2000, sh);
r = fs({ A1: "=B1+1" }, "A1:A3", "down");
ok("fill down shifts a relative row", r.cells.A2 === "=B2+1" && r.cells.A3 === "=B3+1" && r.formulas === 2);
r = fs({ A1: "=B1+1" }, "A1:C1".replace("C1", "C2"), "right");
ok("fill right shifts a relative column", r.cells.B1 === "=C1+1" && r.cells.C1 === "=D1+1");
r = fs({ A1: "=$B$1+B$1+$B1" }, "A1:A3", "down");
ok("fill down: $B$1 fixed, B$1 fixed row, $B1 moves row", r.cells.A3 === "=$B$1+B$1+$B3");
r = fs({ A1: "=$B$1+B$1+$B1+C1" }, "A1:C2", "right");
ok("fill right: $ pins the column, a $ row does not stop a column move", r.cells.C1 === "=$B$1+D$1+$B1+E1");
r = fs({ A1: "=SUM(B1:C2)" }, "A1:A3", "down");
ok("a range moves both ends", r.cells.A3 === "=SUM(B3:C4)");
r = fs({ A1: "=SUM($B$1:C1)" }, "A1:A3", "down");
ok("a range with one pinned end", r.cells.A2 === "=SUM($B$1:C2)");
r = fs({ A1: '=B1&"B1 ""C1"" $A$1"' }, "A1:A2", "down");
ok("text in quotes is not touched, including doubled quotes", r.cells.A2 === '=B2&"B1 ""C1"" $A$1"');
r = fs({ A1: "=LOG10(B1)+1E5+A1.5" }, "A1:A2", "down");
ok("function names, numbers and non-references are not touched", r.cells.A2 === "=LOG10(B2)+1E5+A1.5");
r = fs({ A1: "=b1+ABCD1+Z1000" }, "A1:A2", "down");
ok("lower case is shifted (output upper case); a 4 letter name is not a cell", r.cells.A2.indexOf("=B2+ABCD1+") === 0);
r = fs({ A5: "=A4+1" }, "A1:A5", "down");
ok("a source below the range top copies from the first row only (A1 empty clears)", !("A2" in r.cells));
r = fs({ A1: "=A1000+1", A2: "x" }, "A1:A3", "down");
ok("moving past row 1000 gives #REF! and is counted", r.cells.A2 === "=#REF!+1" && r.refErrs === 2);
r = fs({ B1: "=A1+1" }, "B1:C1", "right");
ok("moving left of column A is not possible on a right fill; col stays valid", r.cells.C1 === "=B1+1" && !r.refErrs);
r = fs({ Z1: "=Z2" }, "Z1:Z2", "down");
ok("no #REF! when it stays on the grid", r.cells.Z2 === "=Z3" && !r.refErrs);
r = fs({ Y1: "=Z1" }, "Y1:Z1", "right");
ok("moving past column Z gives #REF!", r.cells.Z1 === "=#REF!" && r.refErrs === 1);
r = fs({ A1: "=SUM(Y1:Z1)" }, "A1:B1", "right");
ok("a range with one end off the grid becomes one #REF!", r.cells.B1 === "=SUM(#REF!)");
r = fs({ A1: "=ZZ9+A0" }, "A1:A2", "down");
ok("an already out of range reference is left as written", r.cells.A2 === "=ZZ9+A0");
r = fs({ A1: "hello B1" }, "A1:A2", "down");
ok("plain text is never shifted", r.cells.A2 === "hello B1");
ok("shiftFormula: source not starting with = is returned as is", sh("B1", 0, 1) === "B1");
// evaluation: the engine reads $ and #REF!
const G = (cells, a) => String(new F.Sheet(mk(cells)).get(a));
ok("engine: $A$1 evaluates", G({ A1: "5", B1: "=$A$1+1" }, "B1") === "6");
ok("engine: $A1 and A$1 evaluate", G({ A1: "5", B1: "=$A1+A$1" }, "B1") === "10");
ok("engine: a range with $ sums", G({ A1: "1", A2: "2", B1: "=SUM($A$1:A$2)" }, "B1") === "3");
ok("engine: #REF! in a formula shows #REF!", G({ B1: "=#REF!+1" }, "B1") === "#REF!");
ok("engine: a lone $ or $ in the middle of a name still fails", G({ B1: "=$+1" }, "B1") === "#PARSE!" && G({ B1: "=A$+1" }, "B1") === "#PARSE!");
ok("engine: LOG10( is a name with a number, not a cell (LOG is not built, so #NAME?)", G({ B1: "=LOG10(100)" }, "B1") === "#NAME?");
ok("engine: A1B2 style names are not cells", G({ B1: "=A1B2" }, "B1") === "#NAME?");
// end to end: fill then evaluate
r = fs({ A1: "10", A2: "20", A3: "30", B1: "=A1*$C$1", C1: "2" }, "B1:B3", "down");
ok("fill then evaluate: B3 = A3*$C$1 = 60", G(r.cells, "B3") === "60" && r.cells.B3 === "=A3*$C$1");
console.log(n - fails + "/" + n + " fill rows passed");
process.exit(fails ? 1 : 0);
