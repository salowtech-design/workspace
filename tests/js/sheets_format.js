const M = require("../../static/sheets/model.js");
const { parseAddr } = require("../../static/sheets/formula.js");
let fails = 0, n = 0;
const ok = (d, c) => { n++; if (!c) { fails++; console.log("FAIL", d); } };
const mk = (...a) => { const r = M.makeFmt(...a, parseAddr); return r.rule; };
ok("range is normalised", mk("a1 : b2", "on", "", "") && mk("a1 : b2", "on", "", "").range === "A1:B2");
ok("needs a range", M.makeFmt("x", "on", "", "", parseAddr).error);
ok("needs one change", M.makeFmt("A1:A2", "", "", "", parseAddr).error);
ok("rejects unknown align and nf", M.makeFmt("A1:A2", "", "top", "", parseAddr).error && M.makeFmt("A1:A2", "", "", "date", parseAddr).error && M.makeFmt("A1:A2", "maybe", "", "", parseAddr).error);
const rules = [mk("A1:C3", "on", "right", "dec2"), mk("B2:B2", "off", "", "int")];
const f = M.fmtFor(rules, "B2", parseAddr);
ok("later rule overrides one property at a time", f.bold === false && f.align === "right" && f.nf === "int");
ok("outside any rule is empty", Object.keys(M.fmtFor(rules, "D9", parseAddr)).length === 0);
ok("z100 reachable", M.fmtFor([mk("Y99:Z100", "on", "", "")], "Z100", parseAddr).bold === true);
const rt = M.loadFmt(M.fmtJson(rules), parseAddr);
ok("round trips", !rt.unreadable && JSON.stringify(rt.rules) === JSON.stringify(rules));
ok("absent is empty and readable", !M.loadFmt(null, parseAddr).unreadable && M.loadFmt(null, parseAddr).rules.length === 0);
const bad = (raw) => M.loadFmt(raw, parseAddr).unreadable === true;
ok("garbage is unreadable, not empty", bad("{") && bad("[]") && bad('{"v":2,"rules":[]}') && bad('{"v":1}'));
ok("unknown property is unreadable", bad('{"v":1,"rules":[{"range":"A1:A2","bold":true,"font":"x"}]}'));
ok("rule without a property is unreadable", bad('{"v":1,"rules":[{"range":"A1:A2"}]}'));
ok("bad value types are unreadable", bad('{"v":1,"rules":[{"range":"A1:A2","bold":"yes"}]}') && bad('{"v":1,"rules":[{"range":"A1:A2","nf":"date"}]}') && bad('{"v":1,"rules":[{"range":"a1:a2","bold":true}]}'));
ok("too many rules is unreadable", bad(JSON.stringify({ v: 1, rules: Array(21).fill({ range: "A1:A2", bold: true }) })));
let full = []; for (let i = 0; i < M.MAX_FMT; i++) full = M.addFmt(full, mk("A1:A2", "on", "", "")).rules;
ok("limit of 20 rules", M.addFmt(full, mk("A1:A2", "on", "", "")).error);
ok("int", M.fmtText("int", "2.5") === "3" && M.fmtText("int", "-0.2") === "0");
ok("dec2", M.fmtText("dec2", "3") === "3.00" && M.fmtText("dec2", "-0.001") === "0.00");
ok("thousands", M.fmtText("thousands", "1234567.891") === "1,234,567.89" && M.fmtText("thousands", "-5") === "-5.00");
ok("percent", M.fmtText("percent", "0.256") === "25.6%" && M.fmtText("percent", "1") === "100.0%");
ok("text, blanks, errors and general stay as shown", M.fmtText("dec2", "abc") === "abc" && M.fmtText("dec2", "") === "" && M.fmtText("int", "#DIV/0!") === "#DIV/0!" && M.fmtText("general", "1.234") === "1.234" && M.fmtText(undefined, "7") === "7");
ok("12abc and 0x10 are not numbers", M.fmtText("dec2", "12abc") === "12abc" && M.fmtText("dec2", "0x10") === "0x10");
console.log(n - fails + "/" + n + " format rows passed");
process.exit(fails ? 1 : 0);
