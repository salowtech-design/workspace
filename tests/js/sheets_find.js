const M = require("../../static/sheets/model.js");
const F = require("../../static/sheets/formula.js");
let fails = 0, n = 0;
const ok = (d, c) => { n++; if (!c) { fails++; console.log("FAIL", d); } };
const mk = (o) => Object.assign(Object.create(null), o);
const ctxFor = (cells, extra) => { const sh = new F.Sheet(cells); return Object.assign({ parseAddr: F.parseAddr, shown: (a) => sh.get(a), check: null, maxCell: 2000 }, extra || {}); };
const fr = (cells, o, extra) => M.findReplace(cells, o, ctxFor(cells, extra));
let r = fr(mk({ A1: "Apple", A2: "apple pie", B1: "pear" }), { find: "apple", repl: null });
ok("find is case-insensitive by default, in row then column order", r.matched === 2 && r.hits.join() === "A1,A2" && r.changed === 0);
r = fr(mk({ A1: "Apple", A2: "apple pie" }), { find: "apple", repl: null, matchCase: true });
ok("match case finds only the same case", r.hits.join() === "A2");
r = fr(mk({ A1: "Apple", A2: "apple pie", B1: "x" }), { find: "apple", repl: "fig" });
ok("replace all, case-insensitive, one result for every cell", r.cells.A1 === "fig" && r.cells.A2 === "fig pie" && r.cells.B1 === "x" && r.changed === 2);
const base = mk({ A1: "aa" }); fr(base, { find: "a", repl: "b" });
ok("input cells untouched", base.A1 === "aa");
r = fr(mk({ A1: "a.b", A2: "axb" }), { find: "a.b", repl: "Z" });
ok("the text is literal, not a pattern", r.cells.A1 === "Z" && r.cells.A2 === "axb");
r = fr(mk({ A1: "cost", A2: "x cost" }), { find: "cost", repl: "$1 $& $$" });
ok("replacement symbols are literal", r.cells.A1 === "$1 $& $$" && r.cells.A2 === "x $1 $& $$");
ok("an empty find is refused", fr(mk({ A1: "x" }), { find: "", repl: "y" }).error);
r = fr(mk({ A1: "1", A2: "=A1+1" }), { find: "2", repl: "9" });
ok("a formula's shown result is matched but the formula is left alone", r.hits.join() === "A2" && r.resultOnly === 1 && r.changed === 0 && r.cells.A2 === "=A1+1");
r = fr(mk({ A1: "1", A2: "=A1+1" }), { find: "A1", repl: "B1", formulas: true });
ok("with formulas on, the formula text is replaced", r.cells.A2 === "=B1+1" && r.changed === 1);
r = fr(mk({ A1: "1", A2: "=A1+1" }), { find: "2", repl: "9", formulas: true });
ok("with formulas on, the shown result is not searched", r.matched === 0 && r.cells.A2 === "=A1+1");
r = fr(mk({ A1: "x" }), { find: "x", repl: "=1+1" });
ok("typed text does not turn into a formula", r.cells.A1 === "x" && r.becameFormula === 1 && r.changed === 0);
r = fr(mk({ A1: "=SUM(B1)" }), { find: "=", repl: "", formulas: true });
ok("a formula that would lose its = is skipped", r.cells.A1 === "=SUM(B1)" && r.lostEquals === 1);
r = fr(mk({ A1: "ab", A2: "ab" }), { find: "ab", repl: "" });
ok("emptying a cell removes it", !("A1" in r.cells) && !("A2" in r.cells) && r.cleared === 2 && r.changed === 0);
r = fr(mk({ A1: "ab", A2: "ac" }), { find: "a", repl: "bad" }, { check: (a, v) => (a === "A2" ? "no" : null) });
ok("a refused value is counted and the old text stays", r.cells.A1 === "badb" && r.cells.A2 === "ac" && r.refused === 1 && r.changed === 1);
r = fr(mk({ A1: "ab" }), { find: "a", repl: "xxxx" }, { maxCell: 4 });
ok("too long is skipped", r.cells.A1 === "ab" && r.tooLong === 1);
r = fr(mk({ A1: "aaa" }), { find: "aa", repl: "a" });
ok("occurrences do not overlap and are not re-scanned", r.cells.A1 === "aa");
r = fr(mk({ A1: "x" }), { find: "y", repl: "z" });
ok("no match changes nothing", r.matched === 0 && r.cells.A1 === "x");
r = fr(mk({ A1: "Ünï", A2: "ÜNÏ" }), { find: "ünï", repl: null });
ok("case-insensitive for accented letters", r.matched === 2);
const bad = (cells) => ({ badFormula: (a, v) => { const m = Object.assign(Object.create(null), cells); m[a] = v; const x = new F.Sheet(m).get(a); return F.isErr(x) && x.code === "#PARSE!"; } });
const fb = mk({ A1: "1", A2: "=SUM(A1:A1)", A3: "=A1+1" });
r = fr(fb, { find: "A1:A1)", repl: "A1:", formulas: true }, bad(fb));
ok("a replacement that leaves an unreadable formula is skipped and counted", r.cells.A2 === "=SUM(A1:A1)" && r.badFormula === 1 && r.changed === 0);
r = fr(fb, { find: "+", repl: "+*", formulas: true }, bad(fb));
ok("another unreadable result is skipped", r.cells.A3 === "=A1+1" && r.badFormula === 1);
r = fr(fb, { find: "SUM", repl: "SUMX", formulas: true }, bad(fb));
ok("a formula that reads but gives #NAME? is still written (honest limit)", r.cells.A2 === "=SUMX(A1:A1)" && r.changed === 1 && r.badFormula === 0 && F.isErr(new F.Sheet(r.cells).get("A2")));
r = fr(fb, { find: "A1", repl: "B1", formulas: true }, bad(fb));
ok("a readable formula result is written", r.cells.A2 === "=SUM(B1:B1)" && r.cells.A3 === "=B1+1" && r.changed === 2);
console.log(n + " checks, " + fails + " failed"); process.exit(fails ? 1 : 0);
