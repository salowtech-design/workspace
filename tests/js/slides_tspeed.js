const S = require("../../static/slides/model.js");
let n = 0, bad = 0;
const ok = (d, c) => { n++; if (!c) { bad++; console.log("FAIL", d); } };
const J = (x) => JSON.stringify(x);
let d = S.ops.addSlide(S.newDeck(), 0, "blank") || S.newDeck();
if (d.slides.length < 2) d = S.ops.addSlide(S.newDeck(), 0, "title");
const fade = S.ops.setTransition(d, 1, "fade");
ok("a fade with no speed is unchanged: v3, no tspeed key, round-trips", fade.v === 3 && fade.slides[1].tspeed === undefined && J(S.validate(fade)) === J(fade));
ok("setTransitionSpeed refuses a slide that does not fade", S.ops.setTransitionSpeed(d, 1, "slow") === null);
const slow = S.ops.setTransitionSpeed(fade, 1, "slow");
ok("slow is stored on the slide and the deck becomes v10", slow.slides[1].tspeed === "slow" && slow.v === 10);
ok("slow round-trips through validate unchanged", J(S.validate(slow)) === J(slow));
const fast = S.ops.setTransitionSpeed(fade, 1, "fast");
ok("fast is stored and round-trips", fast.slides[1].tspeed === "fast" && J(S.validate(fast)) === J(fast));
ok("normal on a normal fade is a no-op", S.ops.setTransitionSpeed(fade, 1, "normal") === null);
const back = S.ops.setTransitionSpeed(slow, 1, "normal");
ok("back to normal removes the key and the deck drops to v3 again", back.slides[1].tspeed === undefined && back.v === 3 && J(back) === J(fade));
ok("an unknown speed name is refused by the op", S.ops.setTransitionSpeed(fade, 1, "turbo") === null && S.ops.setTransitionSpeed(fade, 1, "") === null);
ok("turning the transition off also removes the speed", (() => { const x = S.ops.setTransition(slow, 1, "none"); return x.slides[1].tspeed === undefined && x.slides[1].transition === undefined && x.v < 3; })());
const raw = (f) => { const x = JSON.parse(J(slow)); f(x.slides[1]); return S.validate(x); };
ok("validate refuses an unknown speed and a speed on a slide with no fade, never drops it", raw((s) => { s.tspeed = "turbo"; }) === null && raw((s) => { delete s.transition; }) === null && raw((s) => { s.tspeed = "normal"; }) === null && raw((s) => { s.tspeed = 5; }) === null);
ok("a v10 deck with the speed removed by hand is just a fade deck and validates", raw((s) => { delete s.tspeed; }) !== null);
ok("version 12 is refused and v10 is accepted", S.validate(Object.assign(JSON.parse(J(slow)), { v: 12 })) === null && S.validate(JSON.parse(J(slow))) !== null);
ok("duplicate slide keeps the speed", (() => { const x = S.ops.duplicateSlide ? S.ops.duplicateSlide(slow, 1) : null; return x && (x.slides[2].tspeed === "slow" && x.v === 10); })());
ok("loadDeck of the stored text keeps the speed", (() => { const r = S.loadDeck(J(slow)); return r.deck && r.deck.slides[1].tspeed === "slow"; })());
console.log(`${n - bad}/${n} tspeed rows passed`);
process.exit(bad ? 1 : 0);
