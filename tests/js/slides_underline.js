// Node rows for Slides underline (deck version 12). Run: node tests/js/slides_underline.js
const path = require("path"), L = require(path.join(__dirname, "../../static/pdf/vendor/pdf-lib.min.js"));
const S = require("../../static/slides/model.js"), P = require("../../static/slides/pdf.js");
let n = 0, bad = 0;
const ok = (d, c) => { n++; if (!c) { bad++; console.log("FAIL", d); } };
const J = (x) => JSON.stringify(x);
(async () => {
  let d = S.ops.addElement(S.newDeck(), 0, "text").deck;
  const id = d.slides[0].elements[0].id;
  d = S.ops.updateElement(d, 0, id, { text: "Hello underline world" });
  ok("an unstyled deck has no u key and stays version 1", d.v === 1 && d.slides[0].elements[0].u === undefined);
  const u = S.ops.updateElement(d, 0, id, { u: true });
  ok("underline is stored as u true and the deck becomes v12", u.slides[0].elements[0].u === true && u.v === 12);
  ok("the stored deck validates to itself", J(S.validate(u)) === J(u));
  ok("a non-boolean u is refused", S.ops.updateElement(d, 0, id, { u: "yes" }) === null && S.ops.updateElement(d, 0, id, { u: 1 }) === null);
  const off = S.ops.updateElement(u, 0, id, { u: false });
  ok("turning it off removes the key and the deck drops back to v1", off.slides[0].elements[0].u === undefined && off.v === 1 && J(off) === J(d));
  const bi = S.ops.updateElement(S.ops.updateElement(u, 0, id, { b: true }), 0, id, { i: true });
  ok("bold, italic and underline together keep all three and v12", bi.slides[0].elements[0].b === true && bi.slides[0].elements[0].i === true && bi.slides[0].elements[0].u === true && bi.v === 12);
  const offBi = S.ops.updateElement(bi, 0, id, { u: false });
  ok("removing only underline leaves bold and italic at v4", offBi.v === 4 && offBi.slides[0].elements[0].b === true && offBi.slides[0].elements[0].i === true && offBi.slides[0].elements[0].u === undefined);
  const dup = S.ops.duplicateElement(u, 0, id);
  ok("duplicate keeps underline", dup.deck.slides[0].elements[1].u === true && dup.deck.v === 12);
  const two = S.ops.duplicateSlide(u, 0);
  ok("duplicate slide keeps underline", two.slides[1].elements[0].u === true);
  ok("a hand-written u that is not true is dropped, not kept", (() => { const raw = JSON.parse(J(d)); raw.slides[0].elements[0].u = "true"; const v = S.validate(raw); return v && v.slides[0].elements[0].u === undefined && v.v === 1; })());
  ok("a version 12 file with u validates, and v13 is still refused", S.validate(u) !== null && S.validate(Object.assign(JSON.parse(J(u)), { v: 13 })) === null);
  const img = JSON.parse(J(u)); img.slides[0].elements[0] = { id: id, type: "image", x: 0, y: 0, w: 100, h: 100, fill: "theme", text: "d", size: 32, img: "a".repeat(64), u: true };
  const vi = S.validate(img); ok("a picture never keeps u", vi && vi.slides[0].elements[0].u === undefined);
  const m1 = S.ops.master_addElement(d, "text"); const mid = m1.id;
  const m2 = S.ops.master_updateElement(m1.deck, mid, { u: true });
  ok("underline on a master item makes the deck v12 and validates", m2.v === 12 && m2.master.elements[0].u === true && J(S.validate(m2)) === J(m2));
  const m3 = S.ops.master_updateElement(m2, mid, { u: false });
  ok("and turning it off leaves the master at its lower version", m3.v < 12);
  // PDF: an underlined line adds one drawn line; the text bytes are the same
  const bytes0 = await P.build(L, S, d), bytes1 = await P.build(L, S, u);
  const raw0 = Buffer.from(bytes0).toString("latin1"), raw1 = Buffer.from(bytes1).toString("latin1");
  ok("PDF builds for both and both are valid PDFs", raw0.startsWith("%PDF-") && raw1.startsWith("%PDF-"));
  const doc1 = await L.PDFDocument.load(bytes1); ok("underlined deck makes one page of 960 x 540", doc1.getPageCount() === 1 && doc1.getPage(0).getWidth() === 960);
  const content = (r) => { const m = r.match(/stream\r?\n([\s\S]*?)endstream/g) || []; return m.join("\n"); };
  const inflate = (bytes) => { const zlib = require("zlib"); const b = Buffer.from(bytes).toString("latin1"); const out = []; const re = /stream\r?\n/g; let m; while ((m = re.exec(b))) { const s = m.index + m[0].length, e = b.indexOf("endstream", s); try { out.push(zlib.inflateSync(Buffer.from(b.slice(s, e), "latin1")).toString("latin1")); } catch (x) {} } return out.join("\n"); };
  const c0 = inflate(bytes0), c1 = inflate(bytes1);
  const strokes = (c) => (c.match(/\sS\r?\n|\sS\s/g) || []).length;
  ok("the underlined PDF draws exactly one more stroked line than the plain one", strokes(c1) === strokes(c0) + 1);
  const long = S.ops.updateElement(u, 0, id, { text: "word ".repeat(40), w: 200, h: 300, size: 16 });
  const cl = inflate(await P.build(L, S, long)), cp = inflate(await P.build(L, S, S.ops.updateElement(long, 0, id, { u: false })));
  const lineCount = S.wrapLines("word ".repeat(40), 16, 200, false).length;
  ok("a wrapped item gets one underline per drawn line (" + lineCount + ")", lineCount > 1 && strokes(cl) - strokes(cp) === lineCount);
  console.log(`${n - bad}/${n} underline rows passed`);
  process.exit(bad ? 1 : 0);
})();
