const M = require("../../static/sheets/model.js");
const { parseAddr } = require("../../static/sheets/formula.js");
let fails = 0, n = 0;
const ok = (d, c) => { n++; if (!c) { fails++; console.log("FAIL", d); } };
const addrOf = (c, r) => String.fromCharCode(64 + c) + r;
const mk = (o) => Object.assign(Object.create(null), o);
const P = (t) => M.parsePaste(t, parseAddr);
ok("a single value is not a block", !M.isBlock("hello") && !M.isBlock("hello\n") && !M.isBlock(""));
ok("tabs or lines make a block", M.isBlock("a\tb") && M.isBlock("a\nb") && M.isBlock("a\r\nb"));
let p = P("a\tb\n1\t2\n");
ok("2x2 with a trailing newline", p.rows === 2 && p.cols === 2 && p.items[1][1] === "2");
p = P("a\tb\r\n1\t2");
ok("CRLF and no final newline", p.rows === 2 && p.items[0][1] === "b");
p = P('"x\ty"\t"line1\nline2"\t"say ""hi"""');
ok("quoted fields keep tabs, newlines and quotes", p.rows === 1 && p.cols === 3 && p.items[0][0] === "x\ty" && p.items[0][1] === "line1\nline2" && p.items[0][2] === 'say "hi"');
ok("unclosed quote is refused", P('"abc\tdef').error);
p = P("a\t\tc\n\t\t");
ok("empty cells stay empty and ragged rows are kept", p.cols === 3 && p.items[0][1] === "" && p.items[1].length === 3);
ok("too many characters is refused", P("x\t".repeat(100001)).error);
ok("too many cells is refused", P(("1\t".repeat(60) + "1\n").repeat(50)).error);
const ap = (cells, text, col, row, check) => M.applyPaste(cells, P(text), col, row, 26, 100, 2000, check, addrOf);
let r = ap(mk({ A1: "old", B1: "keep" }), "x\ty\nz\tw", 1, 1);
ok("writes the block at the start cell", r.cells.A1 === "x" && r.cells.B1 === "y" && r.cells.A2 === "z" && r.cells.B2 === "w" && r.set === 4);
ok("does not mutate the input cells", true);
const base = mk({ A1: "old" }); ap(base, "x\ty", 1, 1); ok("input cells untouched", base.A1 === "old" && !("B1" in base));
r = ap(mk({ A1: "old", B1: "gone" }), "\t", 1, 1);
ok("blank pasted cells clear existing cells", !("A1" in r.cells) && !("B1" in r.cells) && r.cleared === 2);
r = ap(mk({}), "a\tb\tc\n1\t2\t3", 26, 99);
ok("clips at Z100 and counts clipped cells", r.cells.Z99 === "a" && r.cells.Z100 === "1" && !r.cells.AA99 && r.clipped === 4 && r.set === 2);
r = ap(mk({}), "ok\tbad", 1, 1, (a, v) => (v === "bad" ? "no" : null));
ok("validation-refused cells are skipped and counted", r.cells.A1 === "ok" && !("B1" in r.cells) && r.refused === 1);
r = ap(mk({}), "=1+1\t'=x", 1, 1);
ok("a leading = is kept as typed text and counted", r.cells.A1 === "=1+1" && r.formulas === 1 && r.cells.B1 === "'=x");
r = ap(mk({}), "a".repeat(2001) + "\tb", 1, 1);
ok("a value over the cell limit is skipped", !("A1" in r.cells) && r.tooLong === 1 && r.cells.B1 === "b");
r = ap(mk({}), '"a\nb"\tc\r\nd', 1, 1);
ok("a line break inside a pasted cell becomes a space and is counted", r.cells.A1 === "a b" && r.breaks === 1 && r.cells.B1 === "c" && r.cells.A2 === "d");
ok("text after a closing quote refuses the paste", P('"abc"def').error && P('"hello" she said\tx').error && P('"a"\t"b"x').error);
ok("quotes inside plain text and escaped quotes are kept", P('a"b"c\td').items[0][0] === 'a"b"c' && P('"a""b"').items[0][0] === 'a"b' && !P('"ok"\t"x"\n').error);
ok("a quote that is not at the start of a cell is literal", P('5" pipe\tx').items[0][0] === '5" pipe');
ok("currency and percent stay text; = keeps its references", P("$5\t15%\t=A1+B2").items[0].join("|") === "$5|15%|=A1+B2");
console.log(n - fails + "/" + n + " paste rows passed");
process.exit(fails ? 1 : 0);
